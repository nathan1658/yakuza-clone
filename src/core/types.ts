/** Collision membership bits. Use `interactionGroups(member, filter)`. */
export const CG = {
  STATIC: 0x0001,
  CHARACTER: 0x0002,
  PROP: 0x0004,
  DEBRIS: 0x0008,
  /**
   * Combat arena ring: create with interactionGroups(CG.ARENA, CG.CHARACTER). Character sweeps
   * stop at it; the camera, STATIC raycasts, props and debris pass through.
   */
  ARENA: 0x0010,
  ALL: 0xffff,
} as const;

export function interactionGroups(membership: number, filter: number): number {
  return ((membership & 0xffff) << 16) | (filter & 0xffff);
}

export interface RaycastHit {
  point: Vector3;
  normal: Vector3;
  distance: number;
  collider: RAPIER.Collider;
}

/**
 * Kinematic capsule driven by Rapier's KinematicCharacterController.
 * Collides with STATIC colliders only (characters never block each other or
 * props; EntityManager applies soft separation between characters).
 * Autostep 0.3 m, snap-to-ground 0.3 m, slopes ≤ 45°.
 */
export interface ICharacterBody {
  readonly collider: RAPIER.Collider;
  readonly rigidBody: RAPIER.RigidBody;
  /** Foot position (bottom of capsule). Updated after every move/teleport. */
  readonly position: Vector3;
  readonly grounded: boolean;
  /**
   * Move by `displacement` (metres, for this fixed step) with sliding and step-up.
   * No gravity is applied here — the Character integrates vertical velocity itself.
   */
  move(displacement: Vector3): void;
  teleport(footPosition: Vector3): void;
  /** Disabled bodies don't collide and ignore move(). */
  setEnabled(enabled: boolean): void;
  dispose(): void;
}

export interface IPhysicsWorld {
  readonly rapier: typeof RAPIER;
  readonly world: RAPIER.World;
  /** Static oriented box. `rotationY` in radians. */
  createStaticBox(center: Vector3, halfExtents: Vector3, rotationY?: number): RAPIER.Collider;
  createStaticCylinder(center: Vector3, halfHeight: number, radius: number): RAPIER.Collider;
  /** Ground plane / big slab helper. */
  createStaticTrimesh(vertices: Float32Array, indices: Uint32Array): RAPIER.Collider;
  createCharacterBody(footPosition: Vector3, radius: number, height: number): ICharacterBody;
  /**
   * Dynamic box linked to an Object3D: every frame after the physics step the
   * object's world position/quaternion is copied from the body (object must be a
   * direct child of the scene).
   */
  createDynamicBox(
    object: Object3D,
    halfExtents: Vector3,
    opts?: { mass?: number; friction?: number; restitution?: number; groups?: number; linearDamping?: number; angularDamping?: number },
  ): RAPIER.RigidBody;
  removeBody(body: RAPIER.RigidBody): void;
  raycast(origin: Vector3, dir: Vector3, maxDist: number, groups?: number, excludeCollider?: RAPIER.Collider): RaycastHit | null;
  step(fixedDt: number): void;
  /** Copy dynamic body transforms to linked objects (engine calls after step). */
  syncLinked(): void;
}

