/**
 * ============================================================================
 *  MODULE CONTRACT — 古惑仔：銅鑼灣之龍
 * ============================================================================
 *  This file is the single source of truth for every cross-module API.
 *  Modules talk to each other ONLY through:
 *    1. the interfaces below (reached via `GameContext`), and
 *    2. the typed EventBus (`GameEvents`).
 *  Never import a concrete class from another module's directory. The only
 *  place allowed to do that is the composition root `src/core/GameInstance.ts`.
 *
 *  Extending events from inside your own module is allowed via module
 *  augmentation (do NOT edit this file for that):
 *
 *    declare module '../core/types' {
 *      interface GameEvents { 'mymodule:thing': { foo: number } }
 *    }
 *
 *  ---------------------------------------------------------------------------
 *  WORLD CONVENTIONS (everyone must follow these)
 *  ---------------------------------------------------------------------------
 *  - Units: metres, seconds, radians. Y is up.
 *  - North is -Z, south is +Z, east is +X, west is -X.
 *  - Yaw: an entity with yaw θ faces direction (sin θ, 0, cos θ).
 *    yaw 0 faces +Z (south). object3d.rotation.y === yaw.
 *  - A character facing +Z has its RIGHT side toward -X and LEFT toward +X.
 *  - Camera-relative movement: with camera yaw ψ, forward = (sin ψ, 0, cos ψ),
 *    right = (-cos ψ, 0, sin ψ).
 *
 *  RIG / POSE CONVENTIONS (used by entities + combat animation authoring)
 *  - Bind pose: standing upright, facing +Z, arms hanging straight down at the
 *    sides, legs straight. Every limb bone points along -Y in bind pose.
 *  - Pose values are local Euler rotations (order 'XYZ') in radians, applied
 *    RELATIVE to the bind pose.
 *  - Arms / thighs:  X negative  => swing forward (upperArm X = -π/2 points the
 *                                   arm straight forward; thigh X = -1.2 raises knee)
 *                    upperArmL Z positive / upperArmR Z negative => raise sideways
 *  - Forearm:        X negative  => elbow flexes, hand comes forward/up
 *  - Shin:           X positive  => knee bends (foot goes backward)
 *  - Spine/chest/neck/head: X positive => lean/look forward-down,
 *                           Y positive => twist toward character's LEFT (+X)
 *  - `rootOffset` moves the hips relative to their bind height (e.g. [0,-0.4,0]
 *    for a crouch, [0,-0.85,0] lying on the ground combined with hips X ±π/2).
 * ============================================================================
 */
