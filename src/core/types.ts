export interface GameTime {
  /** Scaled delta (0 when paused, <1 in bullet time). Use for gameplay. */
  dt: number;
  /** Unscaled wall-clock delta, clamped to 0.1s. Use for UI/audio/camera easing. */
  realDt: number;
  /** Accumulated scaled time. */
  elapsed: number;
  /** Accumulated real time. */
  realElapsed: number;
  frame: number;
}

/**
 * Every long-lived module implements this. Engine calls, per rendered frame:
 *   fixedUpdate(FIXED_DT) 0..n times (followed by a physics step each time)
 *   update(time)          once, in registration order
 *   lateUpdate(time)      once, in registration order (camera goes here)
 * Constructors must ONLY store `ctx`; never touch other systems before init().
 */
export interface GameSystem {
  readonly name: string;
  init(): Promise<void> | void;
  update(time: GameTime): void;
  fixedUpdate?(fixedDt: number): void;
  lateUpdate?(time: GameTime): void;
  dispose?(): void;
}

export const FIXED_DT = 1 / 60;

