export interface IRenderPipeline {
  render(time: GameTime): void;
  setSize(width: number, height: number, pixelRatio: number): void;
  /**
   * Named full-screen effects, intensity 0..1. Two kinds:
   *  LEVELS (persist until changed; pipeline smooths towards the target):
   *   'heat'       – heat-action look (desaturate + radial blur + orange rim)
   *   'lowHealth'  – desaturated, pulsing red edges when HP is low
   *   'bulletTime' – chromatic aberration + slight blur during slow-mo
   *  IMPULSES (setting starts a pulse that decays by itself in ~0.35 s):
   *   'damage'     – red vignette hit
   *   'flash'      – white impact flash
   * The combat module drives all of these.
   */
  setEffect(name: RenderEffect, intensity: number): void;
}
export type RenderEffect = 'heat' | 'damage' | 'lowHealth' | 'bulletTime' | 'flash';

/**
 * Concrete class: `new GameEngine(container: HTMLElement, input: IInputManager, physics: IPhysicsWorld)`.
 * Per rendered frame:
 *   input.beginFrame(realDt)
 *   repeat while accumulator ≥ FIXED_DT (max 5):  systems.fixedUpdate(FIXED_DT); physics.step(FIXED_DT)
 *   physics.syncLinked()
 *   systems.update(time)      (registration order)
 *   systems.lateUpdate(time)  (registration order)
 *   renderPipeline.render(time)  (or renderer.render(scene, camera) if none)
 *   input.endFrame()
 * When paused or timeScale = 0, no fixed steps run.
 */
export interface IEngine {
  readonly renderer: WebGLRenderer;
  readonly scene: Scene;
  readonly camera: PerspectiveCamera;
  readonly time: Readonly<GameTime>;
  readonly canvas: HTMLCanvasElement;
  /** Gameplay time multiplier (bullet time). 1 = normal. */
  readonly timeScale: number;
  /** When true, scaled dt is 0 (menus). Real time continues. */
  paused: boolean;
  /**
   * Set time scale. If `realDuration` is given, it automatically eases back to 1
   * after that many real seconds.
   */
  setTimeScale(scale: number, realDuration?: number): void;
  addSystem(system: GameSystem): void;
  setRenderPipeline(pipeline: IRenderPipeline): void;
  readonly renderPipeline: IRenderPipeline | null;
  start(): void;
  stop(): void;
}

