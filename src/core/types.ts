/**
 * MOTION OWNERSHIP (the rule that keeps entities/combat/narrative from fighting):
 *  - While `ctx.combat.canMove(c)` is false, COMBAT owns c's desiredVelocity,
 *    facing and animation (attacks, hitstun, knockdown, heat actions...).
 *    Combat must set desiredVelocity itself when it takes over (usually zero).
 *  - Otherwise, an active `moveTo()` owns motion (brain is not ticked meanwhile);
 *  - otherwise the brain / PlayerController owns it.
 *
 * ANIMATION RULE:
 *  - When combatState is 'idle' or 'moving', the Character auto-selects its
 *    locomotion clip every frame from horizontal speed + stance:
 *      stance 'normal': idleClip (still) / walk (<2.2 m/s) / run (<5.5) / sprint
 *      stance 'combat': combatIdle / combatWalkF|B|L|R relative to facing
 *    It will NOT interrupt a non-looping clip that is still playing (a one-shot
 *    'nod', 'pickup', 'drink'...). Once that finishes, locomotion resumes.
 *    To keep an NPC in a looping gesture, set `idleClip` (e.g. 'talk').
 *  - In any other combatState the Character never changes clips on its own.
 */
export interface ICharacter extends IEntity {
  readonly kind: 'character';
  readonly role: CharacterRole;
  readonly faction: Faction;
  readonly displayName: string;
  readonly rig: ICharacterRig;
  readonly body: ICharacterBody;
  readonly radius: number;
  readonly height: number;
  hp: number;
  maxHp: number;
  stats: CombatStats;
  combatState: CombatState;
  /** Seconds in current combatState (combat module resets it). */
  stateTime: number;
  /** Yaw in radians (see conventions). */
  facing: number;
  /** Current persistent desired horizontal velocity (read-only view; use setDesiredVelocity). */
  readonly desiredVelocity: Vector3;
  /** Clip used when standing still in 'normal' stance. */
  idleClip: AnimClip;
  stance: 'normal' | 'combat';
  heldWeapon: IWeaponProp | null;
  brain: ICharacterBrain | null;
  hyperArmor: boolean;
  invulnerable: boolean;
  /** Arbitrary per-module data (e.g. combat AI bookkeeping). */
  readonly userData: Record<string, unknown>;

  isAlive(): boolean;
  getForward(out?: Vector3): Vector3;
  /** Turn towards a point. `maxTurn` limits radians turned this call (omit = snap). */
  faceTowards(point: Vector3, maxTurn?: number): void;
  /**
   * Desired horizontal velocity (m/s) for the next fixed steps. Persistent until
   * changed. The character integrates it with gravity + knockback impulse.
   */
  setDesiredVelocity(v: Vector3): void;
  /** Add an instantaneous velocity (knockback/launch). Horizontal part decays with friction. */
  addImpulse(v: Vector3): void;
  teleport(footPosition: Vector3, yaw?: number): void;
  /**
   * Walk/run in a straight line to `target` (cutscenes & scripted beats).
   * Resolves on arrival (within 0.3 m), when cancelled by another moveTo /
   * teleport, or after `timeoutSec` (default 10). Faces the travel direction.
   */
  moveTo(target: Vector3, speed?: number, timeoutSec?: number): Promise<void>;
  /** Convenience for rig.play(). */
  playAnim(clip: AnimClip | AnimClipDef, opts?: PlayAnimOptions): void;
  /** Capsule used for hit detection (world space). */
  getHurtbox(): { base: Vector3; radius: number; height: number };
  /** Show/hide the whole character (cutscenes). */
  setVisible(visible: boolean): void;
}

